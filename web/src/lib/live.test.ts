import { describe, expect, it } from "vitest"
import type { LiveLane } from "./api"
import { groupLive, itemTitle, shortCommand } from "./live"

const lane = (id: string, laneId: string, ts: string, over: Partial<LiveLane> = {}): LiveLane => ({
  source: "claude-code", id, title: `item ${id}`, cwd: "/w/app", branch: "main", harness: "claude-code", updatedAt: ts,
  project: { key: "app-1", name: "app", worktree: "/w/app" }, lane: laneId, label: laneId, kind: "main", model: "claude-sonnet-4-5",
  nowDoing: { name: "Bash", kind: "tool", summary: "npm test", ts }, startedAt: null, ...over,
})

describe("groupLive", () => {
  it("one group per item, newest activity first, its working lanes nested newest first", () => {
    const g = groupLive([
      lane("a", "main", "2026-11-02T10:00:01Z"),
      lane("b", "main", "2026-11-02T10:00:05Z"),
      lane("a", "qa", "2026-11-02T10:00:09Z"),
      lane("a", "backend", "2026-11-02T09:59:00Z"),
    ])
    expect(g.map((x) => x.id)).toEqual(["a", "b"])
    expect(g[0].lanes.map((l) => l.lane)).toEqual(["qa", "main", "backend"])
    expect(g[0].latest).toBe("2026-11-02T10:00:09Z")
  })
  it("items from different sources with the same id stay apart", () => {
    expect(groupLive([lane("a", "m", "2026-11-02T10:00:00Z"), lane("a", "m", "2026-11-02T10:00:00Z", { source: "native" })])).toHaveLength(2)
  })
})

describe("shortCommand", () => {
  it("drops cd prefixes, shortens absolute paths and hashes, caps at 60 characters", () => {
    expect(shortCommand("cd /Users/someone/work/app && npm test")).toBe("npm test")
    expect(shortCommand("cd /a/b; cd /c/d ;  git status")).toBe("git status")
    expect(shortCommand("cat /Users/someone/work/app/src/lib/thing.ts")).toBe("cat …/lib/thing.ts")
    expect(shortCommand("git show 3f9c2a1b8d7e6f5a4b3c2d1e0f9a8b7c6d5e4f3a")).toBe("git show 3f9c2a1")
    const long = shortCommand("node scripts/run.mjs --flag-one value --flag-two value --flag-three value --flag-four")
    expect(long.length).toBeLessThanOrEqual(60)
    expect(long.endsWith("…")).toBe(true)
    expect(shortCommand("  npm   test  ")).toBe("npm test")
    expect(shortCommand("")).toBe("")
  })
})

describe("itemTitle", () => {
  const at = "2026-11-02T09:05:00Z"
  it("keeps a real title", () => {
    expect(itemTitle({ title: "Add a cart page", id: "x", project: "shop", ts: at })).toBe("Add a cart page")
  })
  it("replaces a bare UUID, the id itself, an empty title or harness-injected text", () => {
    const want = (t: string) => expect(itemTitle({ title: t, id: "sess-1", project: "shop", ts: at })).toMatch(/^Untitled session · shop · \d\d:\d\d$/)
    want("0b6f3a2e-1c4d-4e5f-9a8b-7c6d5e4f3a2b")
    want("sess-1")
    want("")
    want("<command-name>/clear</command-name>")
    want("<local-command-stdout></local-command-stdout>")
    want("Caveat: The messages below were generated by the user while running local commands")
    want("[Request interrupted by user]")
  })
  it("no project: no project part", () => {
    expect(itemTitle({ title: "", id: "s", project: null, ts: null })).toBe("Untitled session")
  })
})
